const makeOptions = (opts: string[]): Option[] =>
  opts.map((opt, i) => ({ id: String.fromCharCode(65 + i), text: opt }));

const q = (
  id: string,
  examId: string,
  subExamId: string,
  testType: TestType,
  subject: string,
  subjectHi: string,
  text: string,
  textHi: string,
  correctOptionId: string,
  optionsEn: string[],
  optionsHi: string[],
  explanationEn: string,
  explanationHi: string,
): Question => ({
  id,
  examId,
  subExamId,
  testType,
  subject,
  subjectHi,
  text,
  textHi,
  correctOptionId,
  options: makeOptions(optionsEn),
  optionsHi: makeOptions(optionsHi),
  explanation: explanationEn,
  explanationHi: explanationHi,
});

